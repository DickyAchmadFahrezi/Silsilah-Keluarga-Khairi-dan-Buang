export const familyData = rawFamilyData.map((item) => {
  const isDeceased =
    Boolean(item.isDeceased) ||
    item.rawName?.includes('(Almarhum)') ||
    item.rawName?.includes('(Almarhumah)');
  
  const deceasedLabel =
    item.deceasedLabel ||
    (item.rawName?.includes('(Almarhumah)') ? 'Almh.' : item.rawName?.includes('(Almarhum)') ? 'Alm.' : null);

  const cleanName = item.name.replace(/\s*\(Almarhum(?:ah)?\)\s*/i, '').trim();

  return {
    ...item,
    name: cleanName,
    isDeceased,
    deceasedLabel,
    parents: item.parents || [],
    spouses: item.spouses || [],
  };
});

export function getPersonById(id, data = familyData) {
  return data.find((p) => p.id === id);
}

export function getSpouses(id, data = familyData) {
  const person = getPersonById(id, data);
  if (!person || !person.spouses) return [];
  return person.spouses.map((sId) => getPersonById(sId, data)).filter(Boolean);
}

export function getParents(id, data = familyData) {
  const person = getPersonById(id, data);
  if (!person || !person.parents) return [];
  return person.parents.map((pId) => getPersonById(pId, data)).filter(Boolean);
}

export function getChildren(id, data = familyData) {
  return data.filter((p) => p.parents && p.parents.includes(id));
}

export function getSiblings(id, data = familyData) {
  const person = getPersonById(id, data);
  if (!person) return [];
  if (person.root) {
    return data.filter((p) => p.root && p.id !== id);
  }
  if (!person.parents || person.parents.length === 0) return [];
  return data.filter(
    (p) =>
      p.id !== id &&
      p.parents &&
      p.parents.some((parent) => person.parents.includes(parent))
  );
}

export function isCousinMarriage(person1Id, person2Id, data = familyData) {
  const p1 = getPersonById(person1Id, data);
  const p2 = getPersonById(person2Id, data);
  if (!p1 || !p2) return false;
  
  // Silang 1: Hanifah & Madji
  if (
    (p1.id === 'hanifah' && p2.id === 'madji') ||
    (p1.id === 'madji' && p2.id === 'hanifah')
  ) {
    return true;
  }

  // Silang 2: Muchsin & Maryanah
  if (
    (p1.id === 'muchsin' && p2.id === 'maryanah') ||
    (p1.id === 'maryanah' && p2.id === 'muchsin')
  ) {
    return true;
  }

  const parents1 = p1.parents || [];
  const parents2 = p2.parents || [];
  if (parents1.length === 0 || parents2.length === 0) return false;

  for (const parent1Id of parents1) {
    const parent1Siblings = getSiblings(parent1Id, data).map((s) => s.id);
    if (parents2.some((parent2Id) => parent1Siblings.includes(parent2Id))) {
      return true;
    }
  }
  return false;
}
